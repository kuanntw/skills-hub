#!/usr/bin/env python3
"""Validate registry data and generate indexes without fetching or executing skills."""
import argparse
import json
from pathlib import Path
import sys

from jsonschema import Draft202012Validator, FormatChecker

ROOT = Path(__file__).resolve().parents[1]
TYPES = {
    "skill-package": "A skill package with a documented entry point; inspect its compatibility before loading.",
    "skill-kit": "Related skill modules with an index or directory entry point.",
    "reference": "A specification or reference document, not an executable skill.",
    "framework": "A methodology or workflow collection, not necessarily a directly loadable skill.",
}


def load_entries(root=ROOT):
    schema = json.loads((root / "schemas/registry.schema.json").read_text(encoding="utf-8"))
    Draft202012Validator.check_schema(schema)
    validator = Draft202012Validator(schema, format_checker=FormatChecker())
    entries = []
    paths = sorted((root / "registry").glob("*.json"))
    if not paths:
        raise ValueError("No registry entries found")
    for path in paths:
        entry = json.loads(path.read_text(encoding="utf-8"))
        errors = sorted(validator.iter_errors(entry), key=lambda e: str(list(e.path)))
        if errors:
            raise ValueError(f"{path.name}: " + "; ".join(e.message for e in errors))
        if entry["id"] != path.stem:
            raise ValueError(f"{path.name}: id must match its filename")
        if entry["source"]["url"] == "https://github.com/kuanntw/skills-hub":
            local_entry = (root / entry["source"]["entry"]).resolve()
            if not local_entry.is_relative_to(root.resolve()) or not local_entry.exists():
                raise ValueError(f"{path.name}: local source entry is missing or escapes the repository")
        entries.append(entry)
    return entries


def markdown_cell(value):
    return value.replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def render_indexes(entries):
    # Keep the existing full JSON shape and schema_version for existing consumers.
    policy = {
        "load_strategy": "progressive_disclosure",
        "first_read": ["skills.catalog.json", "skills.index.md"],
        "then_read": "registry/<skill-id>.json",
        "external_skill_loading": "only_when_relevant",
        "installation_and_execution": "require_separate_authorization_and_environment_policy",
    }
    index = {
        "schema_version": "0.1.0",
        "name": "kuanntw-skills-hub",
        "description": "A routing index for reusable AI skills maintained by kuanntw.",
        "routing_policy": policy,
        "skills": entries,
    }
    compact = {
        "schema_version": "0.1.0",
        "name": index["name"],
        "routing_policy": policy,
        "skills": [
            {**{key: entry[key] for key in ("id", "name", "type", "description")},
             "registry": f"registry/{entry['id']}.json"}
            for entry in entries
        ],
    }
    lines = [
        "# Skills Hub Index", "",
        "<!-- Generated by scripts/build_index.py. Edit registry/*.json, not this file. -->", "",
        "This is a discovery catalog, not permission to install or execute packages.", "",
        "## Routing policy", "",
        "1. Read `skills.catalog.json` or this summary for a lightweight first pass.",
        "2. Read the selected `registry/<skill-id>.json`, including `use_when` and `avoid_when`.",
        "3. Treat trigger and file matches as candidates, not automatic execution decisions.",
        "4. Read only relevant source material. Check separate authorization before installation or execution.",
        "5. Prefer specific skills; use frameworks and references as supporting material.", "",
        "## Available skills", "",
        "| Skill | Type | Description | Source |",
        "|---|---|---|---|",
    ]
    for entry in entries:
        lines.append(f"| [`{entry['id']}`](registry/{entry['id']}.json) | `{entry['type']}` | "
                     f"{markdown_cell(entry['description'])} | <{entry['source']['url']}> |")
    for entry in entries:
        if entry.get("subskills"):
            lines += ["", f"## {entry['name']} subskills", ""]
            lines += [f"- `{subskill}`" for subskill in entry["subskills"]]
    lines += ["", "## Skill type guide", "", "| Type | Meaning |", "|---|---|"]
    lines += [f"| `{kind}` | {meaning} |" for kind, meaning in TYPES.items()]
    return {
        "skills.index.json": json.dumps(index, ensure_ascii=False, indent=2) + "\n",
        "skills.catalog.json": json.dumps(compact, ensure_ascii=False, indent=2) + "\n",
        "skills.index.md": "\n".join(lines) + "\n",
    }


def build(root=ROOT, check=False):
    entries = load_entries(root)
    stale = []
    for name, expected in render_indexes(entries).items():
        path = root / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(name)
        else:
            path.write_text(expected, encoding="utf-8")
    if stale:
        raise ValueError("Generated indexes are stale: " + ", ".join(stale) + "; run python scripts/build_index.py")
    return len(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate without changing files")
    args = parser.parse_args()
    try:
        count = build(check=args.check)
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        return 1
    print(f"Validated {count} registry entries; indexes {'match' if args.check else 'generated'}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
